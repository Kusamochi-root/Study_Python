# Simple Math Operations in Python

# Assigning numbers to variables
x = 100
y = 25

# Performing calculations
sum_result = x + y
sub_result = x - y
mul_result = x * y
div_result = x / y

# Printing the results
print("Addition:", sum_result)       # Result: 125
print("Subtraction:", sub_result)    # Result: 75
print("Multiplication:", mul_result) # Result: 2500
print("Division:", div_result)       # Result: 4.0